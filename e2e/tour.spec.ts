test("kasus contoh menampilkan penolakan tanpa tagihan, pembatalan, TPI, dan label terlarang", async ({ page }) => {
  await page.goto("/pembeli/pesanan");
  await page.getByRole("button", { name: /^Ditolak/ }).click();
  await page.getByRole("link", { name: /TGK-A-0311-R/ }).click();
  await expect(page.locator("main")).toContainText("Insang kusam");
  await expect(page.locator("main")).toContainText("tidak ada tagihan");
  await page.goto("/pembeli/terima/TGK-A-0311-R");
  await page.getByRole("link", { name: "Lihat uang Pak Darman", exact: true }).click();
  await expect(page.getByText("Tidak ada uang masuk dari kiriman ini", { exact: true })).toBeVisible();
  await page.getByRole("link", { name: /Lihat jejak kiriman/ }).click();
  await expect(page.getByText("Kiriman ditolak saat penerimaan", { exact: true })).toBeVisible();
  await expect(page.locator("main")).not.toContainText(/Darman|Pak Rusli/);
  await page.goto("/pembeli/pesanan");
  await page.getByRole("button", { name: /^Dibatalkan/ }).click();
  await expect(page.getByRole("link", { name: /CKL-B-0211-X/ })).toBeVisible();
  await page.goto("/nelayan/tangkapan");
  await expect(page.getByText("Dijual TPI", { exact: true }).first()).toBeVisible();
  await expect(page.getByText("Diolah UMKM", { exact: true }).first()).toBeVisible();
  await page.goto("/umkm/produk/produk-abon-tongkol-belum-lengkap");
  await expect(page.getByText("Hapus klaim mengobati atau menyembuhkan", { exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: /Cetak label/ })).toBeDisabled();
});
